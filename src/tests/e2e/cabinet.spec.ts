import {test,expect} from '@playwright/test'

test('Add item starts a parametric cabinet with exact cutlist and Fusion export',async({page})=>{
 await page.goto('')
 await page.getByRole('button',{name:'+ New project'}).click()
 await page.getByRole('button',{name:'+ Add item'}).click()
 const wizard=page.getByRole('region',{name:'Add furniture item'})
 await expect(wizard.getByText('Live assembly preview')).toBeVisible()
 await expect(wizard.getByText('764 × 350 × 18')).toBeVisible()
 await expect(wizard.getByText('Physical panels')).toBeVisible()
 await wizard.getByRole('button',{name:'Decrease shelves'}).click()
 await wizard.getByRole('button',{name:'Decrease shelves'}).click()
 await expect(wizard.getByLabel('Shelf count')).toHaveText('0')
 await expect(wizard.getByText('Shelf',{exact:true})).toHaveCount(0)
 await wizard.getByRole('button',{name:'Increase shelves'}).click()
 await wizard.getByRole('button',{name:'Increase shelves'}).click()
 await wizard.getByRole('button',{name:'Add item to project'}).click()
 await expect(wizard).toHaveCount(0)
 await expect(page.locator('.parts-list .part-card')).toHaveCount(3)
 await expect(page.locator('.parts-list .part-card').nth(0).getByRole('spinbutton',{name:'Quantity'})).toHaveValue('2')
 await page.reload()
 await expect(page.locator('.parts-list .part-card')).toHaveCount(3)
 await page.getByRole('button',{name:'Open 3D preview'}).click().catch(()=>{})
})

test('Create preset uses wizard and preserves library through reload',async({page})=>{
 await page.goto('')
 await page.getByRole('button',{name:'Presets',exact:true}).click()
 const manager=page.getByRole('region',{name:'Presets'})
 await manager.getByRole('button',{name:'+ Create preset'}).click()
 const wizard=manager.getByRole('region',{name:'Create furniture preset'})
 await wizard.getByRole('textbox',{name:'Preset name'}).fill('Kitchen A')
 await wizard.getByRole('spinbutton',{name:'Overall width (mm)'}).fill('900')
 await wizard.getByRole('button',{name:'Save preset'}).click()
 await expect(wizard).toHaveCount(0)
 await expect(manager.getByText('Cabinet preset saved.')).toBeVisible()
 await page.reload()
 await manager.locator('.preset-category-branch').filter({hasText:'Uncategorized'}).first().locator(':scope > summary').click()
 const saved=manager.locator('.preset-card').filter({hasText:'Kitchen A'})
 await expect(saved).toHaveCount(1)
 await saved.locator('.preset-entry > summary').click()
 await expect(saved.getByText('864 × 350 × 18')).toBeVisible()
 await saved.getByRole('button',{name:'Edit original'}).click()
 await expect(manager.getByRole('region',{name:'Create furniture preset'})).toBeVisible()
})
