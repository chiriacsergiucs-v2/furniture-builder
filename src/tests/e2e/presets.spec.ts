import {test,expect} from '@playwright/test'
test('create, save, reuse across projects and reload preset cut items',async({page})=>{
 await page.goto('')
 await page.getByRole('button',{name:'+ New project'}).click()
 const manager=page.getByRole('region',{name:'Presets'})
 await manager.getByRole('button',{name:'+ Create preset'}).click()
 await manager.getByRole('textbox',{name:'Preset label'}).fill('Drawer top')
 await manager.getByRole('textbox',{name:'Item label'}).fill('Drawer top panel')
 await manager.getByRole('spinbutton',{name:'Width mm'}).fill('470')
 await manager.getByRole('spinbutton',{name:'Height mm'}).fill('220')
 await manager.getByRole('button',{name:'+ Cut item'}).click()
 await manager.getByRole('textbox',{name:'Item label'}).nth(1).fill('Drawer support')
 await manager.getByRole('spinbutton',{name:'Width mm'}).nth(1).fill('130')
 await manager.getByRole('spinbutton',{name:'Height mm'}).nth(1).fill('220')
 await manager.getByRole('button',{name:'Save preset'}).click()
 await expect(manager.getByText('Drawer top',{exact:true}).first()).toBeVisible()
 const drawerPreset=manager.locator('.preset-card').filter({hasText:'Drawer top'})
 await drawerPreset.getByRole('spinbutton',{name:'Sets to add'}).fill('3')
 await drawerPreset.getByRole('button',{name:'Add to project'}).click()
 await expect(page.locator('.part-card').filter({has:page.getByRole('textbox',{name:'Name'})})).toHaveCount(2)
 await expect(page.locator('.part-card').filter({has:page.getByRole('textbox',{name:'Name'})}).first().getByRole('spinbutton',{name:'Quantity'})).toHaveValue('3')
 await page.reload()
 await expect(manager.getByText('Drawer top',{exact:true}).first()).toBeVisible()
 await page.getByRole('button',{name:'Projects',exact:true}).click()
 await page.getByRole('button',{name:'+ New project'}).click()
 await expect(manager.getByText('Drawer top',{exact:true}).first()).toBeVisible()
 await drawerPreset.getByRole('button',{name:'Add to project'}).click()
 await expect(page.locator('.part-card').filter({has:page.getByRole('textbox',{name:'Name'})})).toHaveCount(2)
})
