import {test,expect} from '@playwright/test'

async function showUncategorized(page:import('@playwright/test').Page){
 const branch=page.getByRole('region',{name:'Presets'}).locator('.preset-category-branch').filter({hasText:'Uncategorized'}).first()
 await branch.locator(':scope > summary').click()
 return branch
}
test('create a category preset, persist across reloads and import into distinct projects',async({page})=>{
 await page.goto('')
 await page.getByRole('button',{name:'+ New project'}).click()
 await page.getByRole('button',{name:'Presets',exact:true}).click()
 const manager=page.getByRole('region',{name:'Presets'})
 await manager.getByRole('button',{name:'+ Create preset'}).click()
 const editor=page.getByRole('region',{name:'Preset draft editor'})
 await editor.getByRole('textbox',{name:'Preset label'}).fill('Drawer top')
 await editor.getByRole('textbox',{name:'Item label'}).fill('Drawer top panel')
 await editor.getByRole('spinbutton',{name:'Width mm'}).fill('470')
 await editor.getByRole('spinbutton',{name:'Height mm'}).fill('220')
 await editor.getByRole('button',{name:'+ Cut item'}).click()
 await editor.getByRole('textbox',{name:'Item label'}).nth(1).fill('Drawer support')
 await editor.getByRole('spinbutton',{name:'Width mm'}).nth(1).fill('130')
 await editor.getByRole('spinbutton',{name:'Height mm'}).nth(1).fill('220')
 await editor.getByRole('button',{name:'Save preset'}).click()
 await expect(editor).toHaveCount(0)
 await showUncategorized(page)
 let saved=manager.locator('.preset-card').filter({hasText:'Drawer top'})
 await expect(saved).toHaveCount(1)
 await saved.locator('.preset-entry > summary').click()
 await expect(saved.getByText('Drawer top panel',{exact:false})).toBeVisible()
 await saved.getByRole('spinbutton',{name:'Sets to add'}).fill('3')
 await saved.getByRole('button',{name:'Add to project'}).click()
 await expect(page.getByRole('heading',{name:'Cutlist editor'})).toBeVisible()
 await expect(page.locator('.parts-list .part-card')).toHaveCount(2)
 await expect(page.locator('.parts-list .part-card').first().getByRole('spinbutton',{name:'Quantity'})).toHaveValue('3')
 await page.reload()
 await page.getByRole('button',{name:'Presets',exact:true}).click()
 await showUncategorized(page)
 saved=manager.locator('.preset-card').filter({hasText:'Drawer top'})
 await expect(saved).toHaveCount(1)
 await page.getByRole('button',{name:'Projects',exact:true}).click()
 await page.getByRole('button',{name:'+ New project'}).click()
 await page.getByRole('button',{name:'Presets',exact:true}).click()
 await showUncategorized(page)
 await manager.locator('.preset-card').filter({hasText:'Drawer top'}).locator('.preset-entry > summary').click()
 await manager.locator('.preset-card').filter({hasText:'Drawer top'}).getByRole('button',{name:'Add to project'}).click()
 await expect(page.locator('.parts-list .part-card')).toHaveCount(2)
})

test('duplicate is a new unsaved draft; cancel creates nothing; save creates one independent preset',async({page})=>{
 await page.goto('')
 await page.getByRole('button',{name:'Presets',exact:true}).click()
 const manager=page.getByRole('region',{name:'Presets'})
 const drawers=manager.locator('.preset-category-branch').filter({hasText:'Drawers'}).first()
 await drawers.locator(':scope > summary').click()
 const original=manager.locator('.preset-card').filter({hasText:'40 × 30 cm Drawer'})
 await original.locator('.preset-entry > summary').click()
 await original.getByRole('button',{name:'Duplicate with new params'}).click()
 const draft=manager.getByRole('region',{name:'Preset draft editor'})
 await expect(draft.getByRole('heading',{name:/Duplicate with new params/})).toBeVisible()
 await draft.getByRole('textbox',{name:'Preset label'}).fill('Custom 40 x 30 drawer')
 await draft.getByRole('spinbutton',{name:'Width mm'}).first().fill('310')
 await expect(manager.getByText('1 saved',{exact:false})).toBeVisible()
 await draft.getByRole('button',{name:'Cancel'}).click()
 await expect(draft).toHaveCount(0)
 await page.reload()
 await drawers.locator(':scope > summary').click()
 await original.locator('.preset-entry > summary').click()
 await expect(manager.locator('.preset-card').filter({hasText:'Custom 40 x 30 drawer'})).toHaveCount(0)
 await original.getByRole('button',{name:'Duplicate with new params'}).click()
 await draft.getByRole('textbox',{name:'Preset label'}).fill('Custom 40 x 30 drawer')
 await draft.getByRole('spinbutton',{name:'Width mm'}).first().fill('310')
 await draft.getByRole('button',{name:'Save duplicate'}).click()
 await expect(draft).toHaveCount(0)
 await expect(manager.locator('.preset-card').filter({hasText:'Custom 40 x 30 drawer'})).toHaveCount(1)
 await page.reload()
 await drawers.locator(':scope > summary').click()
 await expect(manager.locator('.preset-card').filter({hasText:'Custom 40 x 30 drawer'})).toHaveCount(1)
 // Open item and request lazy 3D rendering independently of the project editor.
 const copy=manager.locator('.preset-card').filter({hasText:'Custom 40 x 30 drawer'})
 await copy.locator('.preset-entry > summary').click()
 await copy.getByRole('button',{name:'View preset 3D'}).click()
 await expect(copy.getByRole('region',{name:'Preset 3D preview'})).toBeVisible()
})
