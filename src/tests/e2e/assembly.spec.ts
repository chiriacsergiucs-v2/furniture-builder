import {test,expect} from '@playwright/test'

test('starter Drawers category, positioned drawer and XYZ edits persist after reload',async({page})=>{
 await page.goto('')
 await page.getByRole('button',{name:'+ New project'}).click()
 const presets=page.getByRole('region',{name:'Presets'})
 await expect(presets.getByText('40 × 30 cm Drawer',{exact:true}).first()).toBeVisible()
 await page.getByRole('button',{name:'+ 40 × 30 cm Drawer'}).click()
 const assembly=page.getByRole('region',{name:'3D assembly editor'})
 await expect(assembly).toBeVisible()
 await expect(assembly.getByRole('button',{name:'Drawer side #1'})).toBeVisible()
 await expect(assembly.getByRole('button',{name:'Drawer side #2'})).toBeVisible()
 await expect(assembly.getByRole('button',{name:'Front Main #1'})).toBeVisible()
 await assembly.getByRole('button',{name:'Drawer side #1'}).click()
 const x=assembly.getByRole('spinbutton',{name:'X mm'})
 await expect(x).toHaveValue('-159')
 await x.fill('-175')
 await expect(x).toHaveValue('-175')
 await assembly.getByRole('button',{name:'Export Fusion 360 Python'}).click()
 await expect(assembly.getByText(/real panel positions/i)).toBeVisible()
 await page.reload()
 await page.getByRole('button',{name:'Open 3D preview'}).click()
 const restored=page.getByRole('region',{name:'3D assembly editor'})
 await restored.getByRole('button',{name:'Drawer side #1'}).click()
 await expect(restored.getByRole('spinbutton',{name:'X mm'})).toHaveValue('-175')
})
